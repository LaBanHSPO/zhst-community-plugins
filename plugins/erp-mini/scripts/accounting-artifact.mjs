import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';

// Build-time only: retain the shipped migration bytes and SQLite's canonical schema SQL.
const names = ['0001_accounting.sql', '0002_coa_import.sql'];
const reference = new DatabaseSync(':memory:', { enableForeignKeyConstraints: true });
try {
  // Match the Node migration owner's canonical schema after safe table rebuilds.
  // These transaction/PRAGMA statements are build-time only, never runtime SQL.
  reference.exec('PRAGMA foreign_keys=OFF; BEGIN IMMEDIATE;');
  const artifacts = names.map((name, index) => {
    const bytes = readFileSync(new URL(`../migrations/${name}`, import.meta.url));
    const sql = bytes.toString('utf8');
    reference.exec(sql);
    const schema = reference.prepare("SELECT type,name,tbl_name,sql FROM sqlite_schema WHERE name NOT GLOB 'sqlite_*' ORDER BY type,name").all();
    if (schema.length === 0 || schema.some((row) => !row.name.startsWith('erp_ac_') || !row.tbl_name.startsWith('erp_ac_'))) throw new Error('The accounting artifact contains an unexpected schema owner.');
    for (const row of schema) {
      if (row.type !== 'table') continue;
      // Durable migrations defer constraints, never referential actions. Reject
      // future CASCADE/SET NULL additions until their rebuild is designed safely.
      const keys = reference.prepare(`PRAGMA foreign_key_list(${row.name})`).all();
      if (keys.some((key) => key.on_delete !== 'NO ACTION' || key.on_update !== 'NO ACTION')) throw new Error('Durable accounting rebuilds require NO ACTION foreign keys.');
    }
    return { version: index + 1, sql, checksum: createHash('sha256').update(bytes).digest('hex'), schema };
  });
  reference.exec('COMMIT; PRAGMA foreign_keys=ON;');
  if (reference.prepare('PRAGMA foreign_key_check').get()) throw new Error('The accounting artifact has invalid foreign keys.');
  writeFileSync(new URL('../src/accounting/migration.generated.js', import.meta.url), `// Generated by scripts/accounting-artifact.mjs; do not edit.\nexport const accountingMigrations = ${JSON.stringify(artifacts)};\n`);
} finally {
  reference.close();
}
