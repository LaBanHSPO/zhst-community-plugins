import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';

// Build-time only: retain the shipped migration bytes and SQLite's canonical schema SQL.
const bytes = readFileSync(new URL('../migrations/0001_accounting.sql', import.meta.url));
const sql = bytes.toString('utf8');
const reference = new DatabaseSync(':memory:', { enableForeignKeyConstraints: true });
try {
  reference.exec(sql);
  const schema = reference.prepare("SELECT type,name,tbl_name,sql FROM sqlite_schema WHERE name NOT GLOB 'sqlite_*' ORDER BY type,name").all();
  if (schema.length === 0 || schema.some((row) => !row.name.startsWith('erp_ac_') || !row.tbl_name.startsWith('erp_ac_'))) throw new Error('The accounting artifact contains an unexpected schema owner.');
  const artifact = { sql, checksum: createHash('sha256').update(bytes).digest('hex'), schema };
  writeFileSync(new URL('../src/accounting/migration.generated.js', import.meta.url), `// Generated by scripts/accounting-artifact.mjs; do not edit.\nexport const accountingMigration = ${JSON.stringify(artifact)};\n`);
} finally {
  reference.close();
}
